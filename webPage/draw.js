function initCanvas() {
    setCanvasSize();
    ctx.fillStyle = "black";
    ctx.fillRect(0, 0, canvas.width, canvas.height);

    ctx.strokeStyle = "lightgrey";
    ctx.lineWidth = borderWidth;
    for (let i = 0; i <= canvasSize; i++) {
        ctx.moveTo(Math.round(i * gridSize), 0);
        ctx.lineTo(Math.round(i * gridSize), canvas.height);
        ctx.stroke();
    }
    
    for (let i = 0; i <= canvasSize; i++) {
        ctx.moveTo(0, Math.round(i * gridSize));
        ctx.lineTo(canvas.width, Math.round(i * gridSize));
        ctx.stroke();
    }
}

/**
 * 
 * @param {{x: number, y: number}} position 
 */
function updateColour(position) {
    const pos = {
        x: position.x * gridSize + borderWidth,
        y: position.y * gridSize + borderWidth,
    };

    const col = pixelColour[position.x + position.y * canvasSize];
    ctx.fillStyle = `rgb(${col},${col},${col})`;
    ctx.lineWidth = 0;
    ctx.fillRect(pos.x, pos.y, gridSize - borderWidth * 2, gridSize - borderWidth * 2);
}

/**
 * 
 * @param {MouseEvent} e
 */
function mousePosToGrid(e) {
    const rect = canvas.getBoundingClientRect();
    const x = e.clientX - rect.left;
    const y = e.clientY - rect.top;

    const gridPos = {
        x: Math.floor(x / rect.width * canvasSize),
        y: Math.floor(y / rect.height * canvasSize),
    };

    for (let i = -brushSize; i <= brushSize; i++) {
        const posX = gridPos.x - i;
        if (posX < 0 || posX >= canvasSize) {
            continue;
        }
        for (let j = -brushSize; j <= brushSize; j++) {
            const posY = gridPos.y - j;
            if (posY < 0 || posY >= canvasSize) {
                continue;
            }

            const gridCenterPos = {
                x: posX * gridSize + gridSize / 2,
                y: posY * gridSize + gridSize / 2,
            };
            const col = ((gridCenterPos.x - x) ** 2 + (gridCenterPos.y - y) ** 2) ** 0.5 / (brushSize * gridSize)
            pixelColour[posX + posY * canvasSize] += Math.exp(-(col ** 2)) * brushStrength;
            pixelColour[posX + posY * canvasSize] = Math.max(Math.min(Math.round(pixelColour[posX + posY * canvasSize]), 254), 0);
            updateColour({
                x: posX,
                y: posY
            });
        }
    }
}

function updateAll() {
    for (let x = 0; x <= canvasSize; x++) {
        for (let y = 0; y <= canvasSize; y++) {
            updateColour({
                x: x,
                y: y,
            });
        }
    }
}

